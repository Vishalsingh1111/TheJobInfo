// ── Matching ─────────────────────────────────────────────────────────────────
const norm = (s) =>
    String(s || "")
        .normalize("NFD").replace(/[̀-ͯ]/g, "")   // é -> e
        .toLowerCase().replace(/['’]/g, "")                 // Moody's -> moodys
        .replace(/&/g, " and ").replace(/[^a-z0-9]+/g, " ").trim();

// words dropped from a company name before comparing ("Google LLC" -> "google")
const SUFFIX = new Set(["inc", "incorporated", "llc", "ltd", "limited", "pvt", "private", "plc", "corp", "corporation", "co", "company", "gmbh", "ag", "sa", "bv", "nv", "lp", "llp", "pte", "the"]);
const stripSuffix = (tokens) => tokens.filter((t) => !SUFFIX.has(t));

// Single-word names that are also everyday words must match exactly ("Apple", "Apple India"), never "Apple Leisure Group".
// Names with 3 letters or fewer ("HP", "ICE", "UPS", "BP", "ARM", "SAS", "F5") are treated the same way.
const COMMON_WORDS = new Set(["meta", "apple", "visa", "target", "block", "orange", "unity", "shell", "continental", "elastic", "ford", "paramount", "disney", "abbott", "reckitt"]);
// extra words allowed after such a name ("Meta Platforms", "Visa Inc", "Ford Motor Company", "Apple India")
const SAFE_EXTRA = new Set(["india", "indian", "global", "technologies", "technology", "services", "solutions", "software", "labs", "systems", "digital", "platforms", "development", "center", "centre", "research", "bank", "group", "usa", "uk", "us", "motor", "motors", "institute", "business", "enterprise", "enterprises", "automotive", "international", "america", "americas", "europe", "asia", "pacific", "apac", "engineering"]);

const ALIASES = []; // { tokens, strict }
const seenAlias = new Set();
function addAlias(name) {
    const tokens = stripSuffix(norm(name).split(" ").filter(Boolean));
    if (!tokens.length) return;
    const key = tokens.join(" ");
    if (seenAlias.has(key)) return;
    seenAlias.add(key);
    const strict = tokens.length === 1 && (tokens[0].length <= 3 || COMMON_WORDS.has(tokens[0]));
    ALIASES.push({ tokens, strict });
}
const ALL_NAMES = Object.values(POPULAR_COMPANIES).flat();
for (const name of [...ALL_NAMES, ...EXTRA_ALIASES]) {
    addAlias(name);
    // "Tata Group", "Adani Group", "Mahindra Group", "Vodafone Group" also mean every company that starts with that name
    const m = norm(name).match(/^(.+?) group$/);
    if (m && m[1].split(" ").length === 1) addAlias(m[1]);
}

function matchesAlias(companyTokens, { tokens, strict }) {
    if (companyTokens.length < tokens.length) return false;
    for (let i = 0; i < tokens.length; i++) if (companyTokens[i] !== tokens[i]) return false;
    const rest = companyTokens.slice(tokens.length);
    return strict ? rest.every((t) => SAFE_EXTRA.has(t)) : true;
}

// true if the company (or its freehire slug, like "tata-consultancy-services") is on the list above
export function isPopularCompany(name, slug = "") {
    for (const text of [name, slug]) {
        const tokens = stripSuffix(norm(text).split(" ").filter(Boolean));
        if (tokens.length && ALIASES.some((a) => matchesAlias(tokens, a))) return true;
    }
    return false;
}

export const POPULAR_COMPANY_COUNT = new Set(ALL_NAMES.map(norm)).size;